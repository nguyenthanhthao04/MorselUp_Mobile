// Render immutable SVG sources into a native display cache. No artwork,
// root dimensions, paths, filters, or source bytes are changed.
const fs=require('fs'),path=require('path'),crypto=require('crypto');
const {Resvg}=require('@resvg/resvg-js');
const downloads=JSON.parse(fs.readFileSync('design/downloads.json','utf8'));
const output='assets/svg-cache';fs.mkdirSync(output,{recursive:true});
const entries=[],scale=3;
for(let i=0;i<downloads.length;i++){
 const file=downloads[i].file;if(!file.endsWith('.svg'))continue;
 const input=fs.readFileSync('assets/figma/'+file);
 if(!input.includes(Buffer.from('<filter')))continue;
 const sourceHash=crypto.createHash('sha256').update(input).digest('hex');
 const root=input.toString('utf8').match(/<svg\b[^>]*>/)[0];
 const width=Number(root.match(/\bwidth="([\d.]+)"/)?.[1]),height=Number(root.match(/\bheight="([\d.]+)"/)?.[1]);
 if(!(width>0&&height>0))throw new Error('Missing intrinsic dimensions: '+file);
 const rendered=new Resvg(input,{fitTo:{mode:'zoom',value:scale}}).render();
 const png=file.replace(/\.svg$/,'.png');fs.writeFileSync(path.join(output,png),rendered.asPng());
 entries.push({key:'a'+i,file,sourceHash,width,height,scale,png,renderedWidth:rendered.width,renderedHeight:rendered.height});
}
fs.writeFileSync('design/svg-cache.json',JSON.stringify(entries,null,2));
fs.writeFileSync('src/svg-cache.ts','// Native render cache of the original filtered SVGs; generated by scripts/cache-svg-filters.cjs.\nexport const svgCache:Record<string,number>={\n'+entries.map(e=>` ${e.key}:require('../assets/svg-cache/${e.png}'),`).join('\n')+'\n};\n');
console.log('Cached',entries.length,'original filtered SVGs at',scale+'x.');
